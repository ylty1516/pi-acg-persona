#Requires -Version 5.1
<#
.SYNOPSIS
  把 pi-acg-persona 里的人设卡装进 pi 的全局 APPEND_SYSTEM.md。

.DESCRIPTION
  生成的 <agent-dir>/APPEND_SYSTEM.md = 人设卡 + 公共行为约定。
  目标目录按 PI_CODING_AGENT_DIR 解析，未设置时用 ~/.pi/agent。
  任何写操作前都会先备份到本仓库的 .backup/，备份失败则中止。

.EXAMPLE
  .\install.ps1 -List

.EXAMPLE
  .\install.ps1 -Use example

.EXAMPLE
  .\install.ps1 -Status

.EXAMPLE
  .\install.ps1 -Uninstall
#>
[CmdletBinding()]
param(
    [switch]$List,
    [string]$Use,
    [switch]$Status,
    [switch]$Uninstall,
    [string]$AgentDir
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version 2.0

try { [Console]::OutputEncoding = [System.Text.Encoding]::UTF8 } catch { }

$script:RepoRoot = $PSScriptRoot
$script:MarkerPrefix = '<!-- generated by pi-acg-persona : '
$script:TargetName = 'APPEND_SYSTEM.md'

# ---------------------------------------------------------------- helpers

function Write-Help {
    Write-Host @'
pi-acg-persona —— pi 全局二次元人设卡安装器

用法:
  .\install.ps1 -List               列出可用的人设卡 id
  .\install.ps1 -Use <name>         安装/切换人设卡（覆盖前自动备份）
  .\install.ps1 -Status             报告当前生效的人设卡
  .\install.ps1 -Uninstall          卸载（有备份则还原最近一次，否则删除）

可选:
  -AgentDir <path>                  指定 pi agent 目录
                                    （默认读 PI_CODING_AGENT_DIR，否则 ~/.pi/agent）

改完需要回到 pi 里执行 /reload 才生效。
'@
}

function Resolve-AgentDir {
    if ($AgentDir) { return $AgentDir }
    if ($env:PI_CODING_AGENT_DIR) { return $env:PI_CODING_AGENT_DIR }
    return (Join-Path (Join-Path $HOME '.pi') 'agent')
}

function Get-PersonaIds {
    $dir = Join-Path $script:RepoRoot 'personas'
    if (-not (Test-Path -LiteralPath $dir)) { return @() }
    return @(
        Get-ChildItem -LiteralPath $dir -Filter '*.md' -File |
            Sort-Object Name |
            ForEach-Object { $_.BaseName }
    )
}

function ConvertTo-Lf([string]$Text) {
    if ([string]::IsNullOrEmpty($Text)) { return '' }
    return (($Text -replace "`r`n", "`n") -replace "`r", "`n").TrimEnd("`n")
}

function Read-Text([string]$Path) {
    if (-not (Test-Path -LiteralPath $Path)) { throw "找不到文件: $Path" }
    return (Get-Content -LiteralPath $Path -Raw -Encoding UTF8)
}

function Write-TextNoBom([string]$Path, [string]$Text) {
    $enc = New-Object System.Text.UTF8Encoding($false)
    [System.IO.File]::WriteAllText($Path, $Text, $enc)
}

function Get-Sha256([string]$Text) {
    $bytes = [System.Text.Encoding]::UTF8.GetBytes((ConvertTo-Lf $Text))
    $sha = [System.Security.Cryptography.SHA256]::Create()
    try {
        $hash = $sha.ComputeHash($bytes)
    }
    finally {
        $sha.Dispose()
    }
    return ([System.BitConverter]::ToString($hash) -replace '-', '').ToLowerInvariant()
}

function Build-Content([string]$Name) {
    $basePath = Join-Path (Join-Path $script:RepoRoot 'base') 'behavior.md'
    $personaPath = Join-Path (Join-Path $script:RepoRoot 'personas') "$Name.md"

    $base = ConvertTo-Lf (Read-Text $basePath)
    $persona = ConvertTo-Lf (Read-Text $personaPath)

    $marker = "$script:MarkerPrefix$Name -->"
    $parts = @(
        $marker
        ''
        $persona
        ''
        '---'
        ''
        '# 公共行为约定'
        ''
        $base
        ''
    )
    return ($parts -join "`n")
}

function Get-TargetTag([string]$Target) {
    $dir = (Split-Path -Parent $Target).TrimEnd('\', '/')
    return (Get-Sha256 $dir.ToLowerInvariant()).Substring(0, 8)
}

function Backup-Target([string]$Target) {
    if (-not (Test-Path -LiteralPath $Target)) { return $null }
    $backupDir = Join-Path $script:RepoRoot '.backup'
    if (-not (Test-Path -LiteralPath $backupDir)) {
        New-Item -ItemType Directory -Path $backupDir -Force | Out-Null
    }
    $stamp = Get-Date -Format 'yyyyMMdd-HHmmss'
    $dest = Join-Path $backupDir "APPEND_SYSTEM.$(Get-TargetTag $Target).$stamp.md"
    Copy-Item -LiteralPath $Target -Destination $dest -Force
    if (-not (Test-Path -LiteralPath $dest)) {
        throw "备份失败，已中止，未改动任何文件: $dest"
    }
    return $dest
}

function Get-CurrentMarkerName([string]$Text) {
    $normalized = ConvertTo-Lf $Text
    $firstLine = ($normalized -split "`n" | Select-Object -First 1)
    if ($firstLine -and $firstLine.StartsWith($script:MarkerPrefix)) {
        return ($firstLine.Substring($script:MarkerPrefix.Length) -replace '\s*-->\s*$', '')
    }
    return $null
}

# ---------------------------------------------------------------- actions

function Invoke-List {
    $ids = @(Get-PersonaIds)
    if ($ids.Count -eq 0) {
        Write-Host 'personas/ 下还没有人设卡。可以从 persona.template.md 抄一份。'
        return
    }
    Write-Host '可用的人设卡:'
    foreach ($id in $ids) {
        Write-Host "  - $id"
    }
}

function Invoke-Use([string]$Name) {
    $name = $Name.Trim()
    if ($name.EndsWith('.md')) { $name = $name.Substring(0, $name.Length - 3) }

    $ids = @(Get-PersonaIds)
    if ($ids -notcontains $name) {
        throw "没有这个人设卡: '$name'。可用: $($ids -join ', ')"
    }

    $target = Join-Path (Resolve-AgentDir) $script:TargetName
    $agentDir = Split-Path -Parent $target
    if (-not (Test-Path -LiteralPath $agentDir)) {
        New-Item -ItemType Directory -Path $agentDir -Force | Out-Null
    }

    $backup = Backup-Target $target
    Write-TextNoBom $target (Build-Content $name)

    Write-Host ''
    Write-Host "人设卡已生效: $name"
    Write-Host "  写入: $target"
    if ($backup) { Write-Host "  备份: $backup" } else { Write-Host '  备份: （此前无文件，无需备份）' }
    Write-Host ''
    Write-Host ' 回 pi 里执行 /reload 生效（新开窗口会自动加载）。'
}

function Invoke-Status {
    $target = Join-Path (Resolve-AgentDir) $script:TargetName
    Write-Host "目标文件: $target"

    if (-not (Test-Path -LiteralPath $target)) {
        Write-Host '当前状态: 未安装（该文件不存在）'
        return
    }

    $current = Read-Text $target
    $name = Get-CurrentMarkerName $current

    if (-not $name) {
        Write-Host '当前状态: 非本仓库管理（文件里没有 pi-acg-persona 生成标记）'
        return
    }

    if (@(Get-PersonaIds) -notcontains $name) {
        Write-Host "当前状态: 生成标记写着 '$name'，但 personas/ 下没有这张卡"
        return
    }

    if ((Get-Sha256 $current) -eq (Get-Sha256 (Build-Content $name))) {
        Write-Host "当前状态: 生效中 → $name"
    }
    else {
        Write-Host "当前状态: $name（文件已与仓库不一致，被手动改过或仓库有更新）"
        Write-Host '         重新执行 -Use 即可覆盖，覆盖前会自动备份。'
    }
}

function Get-NewestBackup([string]$Target) {
    $backupDir = Join-Path $script:RepoRoot '.backup'
    if (-not (Test-Path -LiteralPath $backupDir)) { return $null }
    $pattern = "APPEND_SYSTEM.$(Get-TargetTag $Target).*.md"
    $latest = Get-ChildItem -LiteralPath $backupDir -Filter $pattern -File |
        Sort-Object Name -Descending |
        Select-Object -First 1
    if (-not $latest) { return $null }
    return $latest.FullName
}

function Invoke-Uninstall {
    $target = Join-Path (Resolve-AgentDir) $script:TargetName
    if (-not (Test-Path -LiteralPath $target)) {
        Write-Host '当前没有安装任何东西，无需卸载。'
        return
    }

    $previous = Get-NewestBackup $target
    if ($previous) {
        # 撤销上一次安装：还原到安装前的文件，而不是直接删掉用户原本的内容
        Copy-Item -LiteralPath $previous -Destination $target -Force
        Remove-Item -LiteralPath $previous -Force   # 备份已被消费，避免重复回退到同一个状态
        Write-Host '已还原到安装前的文件（撤销最近一次安装）。'
        Write-Host "  从: $previous"
        Write-Host "  到: $target"
        Write-Host ''
        Write-Host ' 再执行一次本命令可以继续往前回退一步。'
        return
    }

    if (-not (Get-CurrentMarkerName (Read-Text $target))) {
        Write-Host '没有可回退的备份了，当前文件也不是本工具生成的，已原样保留。'
        Write-Host "  如需删除请手动处理: $target"
        return
    }

    Remove-Item -LiteralPath $target -Force
    Write-Host '已卸载（无历史备份，人设文件已删除）。'
}

# ---------------------------------------------------------------- dispatch

$actions = @()
if ($List) { $actions += 'List' }
if ($Use) { $actions += 'Use' }
if ($Status) { $actions += 'Status' }
if ($Uninstall) { $actions += 'Uninstall' }

if ($actions.Count -eq 0) {
    Write-Help
    return
}
if ($actions.Count -gt 1) {
    Write-Error "一次只能做一个动作，收到了: $($actions -join ', ')" -ErrorAction Continue
    exit 1
}

try {
    switch ($actions[0]) {
        'List' { Invoke-List }
        'Use' { Invoke-Use $Use }
        'Status' { Invoke-Status }
        'Uninstall' { Invoke-Uninstall }
    }
}
catch {
    Write-Host ''
    Write-Host "出错了: $($_.Exception.Message)" -ForegroundColor Red
    exit 1
}